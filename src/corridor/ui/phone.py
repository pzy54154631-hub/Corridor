"""Simulated phone page and synthetic SMS copies; display only, never an approval path.

The banking session reads the verifier's code once (under the verifier lock, the same
read-only access the device panel used) and writes an immutable synthetic SMS copy to
the process-local outbox. The phone page is a separate browser session: it only
reads that outbox and never creates or touches a controller, gateway or verifier.
The SMS summary is generated by the display layer from the same canonical card; the
gateway binds the code to the action and card hash and does not verify SMS text.
"""

import secrets
from html import escape
from typing import Any

import streamlit as st

from corridor.i18n import LOCALES, get_locale, reset_locale, set_locale
from corridor.ui import display_names, view_mode
from corridor.ui.components import KINDS, money
from corridor.ui.messages import tr
from corridor.ui.phone_outbox import OUTBOX, SimulatedSMS, sms_ref

PAIR_KEY = "phone_pair"
MASK = "•" * 6
TRANSFER_KINDS = frozenset({"transfer", "schedule_transfer"})
AUTOSUBMIT_SCRIPT = """<script>
const d = window.parent.document;
if (d.__corridorOtpHandler) d.removeEventListener('input', d.__corridorOtpHandler, true);
const handler = (e) => {
  const el = e.target;
  if (!el || el.tagName !== 'INPUT' || el.autocomplete !== 'one-time-code') return;
  if (!/^\\d{6}$/.test(el.value)) return;
  const form = el.closest('[data-testid="stForm"]');
  const btn = form && form.querySelector('[data-testid="stFormSubmitButton"] button');
  if (btn) setTimeout(() => btn.click(), 60);
};
d.__corridorOtpHandler = handler;
d.addEventListener('input', handler, true);
window.addEventListener('pagehide', () => {
  if (d.__corridorOtpHandler === handler) {
    d.removeEventListener('input', handler, true);
    d.__corridorOtpHandler = null;
  }
});
</script>"""


def pair_token() -> str:
    """A per-browser-session demo pairing token; never part of state, audit or prompts."""
    token = st.session_state.get(PAIR_KEY)
    if not isinstance(token, str) or not token:
        token = secrets.token_urlsafe(16)
        st.session_state[PAIR_KEY] = token
    return token


def _contact(card: dict[str, Any], state: Any) -> Any:
    reference = (card.get("objects") or {}).get("contact_ref")
    return getattr(state, "contacts", {}).get(str(reference)) if reference else None


def _localized_fields(
    card: dict[str, Any] | None, kind: str, state: Any
) -> tuple[str, dict[str, str]]:
    """Choose the template and its display values from the canonical card only."""
    card = card or {}
    objects = card.get("objects") or {}
    amount = card.get("amount")
    if kind == "unlock":
        return "polish.sms.unlock", {}
    if kind in TRANSFER_KINDS:
        parts = display_names.contact_parts(objects.get("contact_ref"), state)
        if parts is not None and parts[1] is not None and amount is not None:
            return "polish.sms.transfer", {
                "payee": parts[0],
                "tail": parts[1],
                "action": tr(KINDS.get(kind, "Business approval")),
                "amount": money(amount),
            }
    if kind == "purchase_product" and amount is not None:
        product = objects.get("product_ref")
        name = display_names.label(product, state, trace=False) if product else None
        return "polish.sms.purchase", {
            "product": name or str(product or "—"),
            "amount": money(amount),
        }
    return "polish.sms.generic", {
        "action": tr(KINDS.get(kind, "Business approval")),
        "amount": money(amount) if amount is not None else "",
    }


def build_sms(
    challenge_id: str,
    *,
    code: str,
    expiry: str,
    kind: str,
    card: dict[str, Any] | None = None,
    state: Any = None,
) -> SimulatedSMS:
    """Assemble an immutable synthetic SMS in every display locale; reads only."""
    template = "polish.sms.generic"
    localized: list[tuple[str, tuple[tuple[str, str], ...]]] = []
    for locale in LOCALES:
        token = set_locale(locale)
        try:
            template, values = _localized_fields(card, kind, state)
        finally:
            reset_locale(token)
        localized.append((locale, tuple(sorted(values.items()))))
    contact = _contact(card or {}, state)
    new_payee = kind in TRANSFER_KINDS and (
        "new_recipient" in ((card or {}).get("tier_reasons") or [])
        or bool(getattr(contact, "is_new", False))
    )
    return SimulatedSMS(
        ref=sms_ref(challenge_id),
        kind=kind,
        template=template,
        fields=tuple(localized),
        code=code,
        expiry=expiry,
        notes=("polish.sms.new_payee",) if new_payee else (),
    )


def _read_challenge(controller: Any, challenge_id: str) -> tuple[str, str] | None:
    """Read code and expiry under the verifier lock; never reset attempts or issue a grant."""
    verifier = controller.gateway.mfa
    with verifier._lock:
        challenge = verifier._challenges.get(challenge_id)
        if challenge is None:
            return None
        return verifier.test_code(challenge_id), challenge.expiry


def deliver(
    controller: Any, challenge_id: str, *, kind: str, card: dict[str, Any] | None = None
) -> None:
    """Idempotently place this challenge's synthetic SMS in this session's phone inbox."""
    read = _read_challenge(controller, challenge_id)
    if read is None:
        return
    code, expiry = read
    OUTBOX.deliver(
        pair_token(),
        build_sms(
            challenge_id,
            code=code,
            expiry=expiry,
            kind=kind,
            card=card,
            state=getattr(controller, "state", None),
        ),
    )


def retire(challenge_id: Any, status: str) -> None:
    """Mark this session's SMS copy used or expired; its code is no longer shown."""
    pair = st.session_state.get(PAIR_KEY)
    if isinstance(pair, str) and pair and isinstance(challenge_id, str) and challenge_id:
        OUTBOX.mark(pair, sms_ref(challenge_id), status)


def sms_text(sms: SimulatedSMS, *, locale: str | None = None) -> str:
    """Render one copy in a locale; a used or expired copy never shows its code."""
    language = locale or get_locale()
    values = sms.values(language)
    token = set_locale(language)
    try:
        text = tr(
            sms.template,
            **values,
            code=sms.code if sms.status == "active" and sms.code else MASK,
            expiry=display_names.beijing(sms.expiry) if sms.expiry else "—",
        )
        return " ".join([text, *(tr(note) for note in sms.notes)])
    finally:
        reset_locale(token)


def render_sent() -> None:
    st.info(tr("polish.phone.sent"))
    render_link()


def render_link() -> None:
    pair = pair_token()
    OUTBOX.register(pair)
    view = "judge" if view_mode.is_judge() else "customer"
    st.link_button(tr("polish.phone.open"), f"?phone={pair}&view={view}")


def autosubmit() -> None:
    """Inject the six-digit auto-submit listener at most once per script run."""
    if not view_mode.claim_once("phone.autosubmit"):
        return
    import streamlit.components.v1 as components

    components.html(AUTOSUBMIT_SCRIPT, height=0)


def _bubble(sms: SimulatedSMS, *, latest: bool) -> str:
    classes = "sms-bubble" + (" sms-latest" if latest else "")
    if sms.status != "active":
        classes += " sms-closed"
    status = {"used": tr("polish.phone.used"), "expired": tr("polish.phone.expired")}.get(
        sms.status, ""
    )
    otp = f' data-otp="{escape(sms.code)}"' if latest and sms.status == "active" else ""
    return (
        f'<div class="{classes}"{otp}>'
        f'<div class="sms-sender">{escape(tr("polish.phone.sender"))}</div>'
        f"<div>{escape(sms_text(sms))}</div>"
        + (f'<div class="sms-status">{escape(status)}</div>' if status else "")
        + "</div>"
    )


def phone_html(pair: str, *, judge: bool) -> str:
    """The whole simulated phone screen for one pairing, read only from the outbox."""
    body = []
    if not OUTBOX.known(pair):
        body.append(f'<div class="sms-status">{escape(tr("polish.phone.unpaired"))}</div>')
    else:
        messages = OUTBOX.inbox(pair)
        if not messages:
            body.append(f'<div class="sms-status">{escape(tr("polish.phone.empty"))}</div>')
        latest = next((sms for sms in messages if sms.status == "active"), None)
        if latest is not None:
            body.append(_bubble(latest, latest=True))
        body.extend(_bubble(sms, latest=False) for sms in messages if sms is not latest)
    footer = escape(tr("polish.phone.footer"))
    disclosure = (
        f'<div class="sim-phone-footer">{escape(tr("polish.phone.disclosure"))}</div>'
        if judge
        else ""
    )
    return (
        '<div class="sim-phone-frame">'
        f'<div class="sim-phone-status"><span>{escape(tr("polish.phone.status_bar"))}</span>'
        "<span>●●●</span></div>"
        f'<div class="sim-phone-title">{escape(tr("polish.phone.title"))}</div>'
        + "".join(body)
        + f'<div class="sim-phone-footer">{footer}</div>{disclosure}</div>'
    )


@st.fragment(run_every="1s")
def _phone_screen(pair: str) -> None:
    view_mode.reapply()
    st.markdown(phone_html(pair, judge=view_mode.is_judge()), unsafe_allow_html=True)


def phone_route() -> bool:
    """Render only the simulated phone for ``?phone=<pair>``; never create a controller."""
    pair = st.query_params.get("phone")
    if not pair:
        return False
    with st.container(key="sim_phone"):
        _phone_screen(str(pair))
    return True
